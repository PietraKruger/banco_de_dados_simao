public class ExerciciosVariaveis {

  public static void main(String[] args) {
    int x = 10;

    int y = 20;

    int adicao = x + y;

    int subtracao = x - y;

    int multiplicacao = x * y;

    int divisao = x / y;

    System.out.println(adicao);
    System.out.println(subtracao);
    System.out.println(multiplicacao);
    System.out.println(divisao);
  }
}
